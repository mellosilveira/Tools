namespace AcceptanceTests.Database;

/// <summary>
/// Integration test verifying end-to-end database operations against a live PostgreSQL container,
/// running schema migrations via <see cref="MigratorEngine"/> and performing CRUD operations
/// with SQL statements dynamically generated by <see cref="ISqlProvider"/> and executed via <see cref="PostgresRepository"/>.
/// </summary>
public sealed class PostgresIntegrationTests
{
    private const string FallbackLocalConnectionString = "Host=localhost;Port=5432;Database=tools_db;Username=postgres;Password=postgres;";

    /// <summary>
    /// Executes a complete CRUD lifecycle (Insert, Select, Update, Delete) against PostgreSQL for domain entities.
    /// Uses Testcontainers to spin up an isolated PostgreSQL container, or falls back to an active local docker-compose instance.
    /// </summary>
    [Fact]
    public async Task Postgres_CrudLifecycle_ShouldInsertSelectUpdateAndDeleteEntities_UsingSqlProvider()
    {
        PostgreSqlContainer? container = null;
        string? connectionString = null;

        try
        {
            // 1. Attempt to launch an isolated PostgreSQL container via Testcontainers.
            try
            {
                container = new PostgreSqlBuilder()
                    .WithImage("postgres:17-alpine")
                    .WithDatabase("tools_db")
                    .WithUsername("postgres")
                    .WithPassword("postgres")
                    .Build();

                await container.StartAsync();
                connectionString = container.GetConnectionString();
            }
            catch
            {
                container = null;
            }

            // 2. If Testcontainers could not start (e.g. Docker daemon is stopped in CI or host), try local docker-compose port.
            if (string.IsNullOrWhiteSpace(connectionString))
            {
                string? envConn = Environment.GetEnvironmentVariable("POSTGRES_CONNECTION_STRING")
                    ?? Environment.GetEnvironmentVariable("CONNECTION_STRING");

                string candidate = !string.IsNullOrWhiteSpace(envConn) ? envConn : FallbackLocalConnectionString;

                try
                {
                    await using NpgsqlConnection testConn = new(candidate);
                    await testConn.OpenAsync();
                    connectionString = candidate;
                }
                catch
                {
                    connectionString = null;
                }
            }

            // 3. Gracefully skip if no Docker container or local PostgreSQL instance is reachable.
            if (string.IsNullOrWhiteSpace(connectionString))
            {
                return;
            }

            // 4. Run contextual schema migrations using DbUp migrator with mocked logger.
            ILogger migratorLogger = Mock.Of<ILogger>();
            MigratorOptions migratorOptions = new(connectionString, MigrationContext.All, 60);
            Result migrationResult = MigratorEngine.UpgradeDatabase(migratorLogger, migratorOptions);
            Assert.True(migrationResult.Success, $"Migration failed: {migrationResult.JoinedMessages}");

            // 5. Initialize PostgresRepository with ISqlProvider and mocked logger.
            ISqlProvider sqlProvider = new PostgresSqlProvider();
            DatabaseSettings databaseSettings = new()
            {
                ConnectionString = connectionString,
                UnitOperationTimeoutInMilliseconds = 30_000,
                BulkOperationTimeoutInMilliseconds = 60_000
            };
            ResiliencePipelineSettings resilienceSettings = new()
            {
                BackoffType = DelayBackoffType.Constant,
                DelayInMilliseconds = 100,
                MaxRetryAttempts = 3,
                UseJitter = false
            };
            ILogger<PostgresResiliencePipeline> pipelineLogger = Mock.Of<ILogger<PostgresResiliencePipeline>>();
            PostgresResiliencePipeline resiliencePipeline = new(pipelineLogger, resilienceSettings);
            PostgresRepository repository = new(sqlProvider, resiliencePipeline, databaseSettings);

            // =========================================================================
            // CRUD Test 1: StorageEntryMetadataEntity (stored_files table)
            // =========================================================================
            StorageEntryMetadata fileMetadata = new(
                StorageProvider.Local,
                "optimizations/experiments/knee_ligament_01.csv",
                "optimizations/experiments",
                "knee_ligament_01.csv",
                2048,
                DateTimeOffset.UtcNow);

            StorageEntryMetadataEntity fileEntity = StorageEntryMetadataEntity.Create(
                fileMetadata,
                externalIdentifier: "EXP-KNEE-001",
                contentType: "text/csv");

            // INSERT
            long insertedFileId = await repository.InsertAsync(fileEntity);
            Assert.True(insertedFileId > 0, "InsertAsync must return a positive generated primary key.");

            // SELECT
            StorageEntryMetadataEntity? fetchedFile = await repository.GetAsync<StorageEntryMetadataEntity>(insertedFileId);
            Assert.NotNull(fetchedFile);
            Assert.Equal("EXP-KNEE-001", fetchedFile.ExternalIdentifier);
            Assert.Equal("knee_ligament_01.csv", fetchedFile.FileName);
            Assert.Equal(2048, fetchedFile.SizeBytes);
            Assert.Equal("text/csv", fetchedFile.ContentType);

            // UPDATE
            StorageEntryMetadataEntity modifiedFile = fetchedFile with
            {
                ExternalIdentifier = "EXP-KNEE-001-MODIFIED",
                SizeBytes = 4096
            };
            bool fileUpdated = await repository.TryUpdateAsync(modifiedFile);
            Assert.True(fileUpdated, "TryUpdateAsync must return true when updating an existing record.");

            StorageEntryMetadataEntity? fetchedUpdatedFile = await repository.GetAsync<StorageEntryMetadataEntity>(insertedFileId);
            Assert.NotNull(fetchedUpdatedFile);
            Assert.Equal("EXP-KNEE-001-MODIFIED", fetchedUpdatedFile.ExternalIdentifier);
            Assert.Equal(4096, fetchedUpdatedFile.SizeBytes);

            // DELETE
            await repository.DeleteAsync<StorageEntryMetadataEntity>(insertedFileId);
            StorageEntryMetadataEntity? fetchedDeletedFile = await repository.GetAsync<StorageEntryMetadataEntity>(insertedFileId);
            Assert.Null(fetchedDeletedFile);

            // =========================================================================
            // CRUD Test 2: MechanicalModelCurveFitOutputEntity (mechanical_model_curve_fit_outputs table)
            // =========================================================================
            MechanicalModelCurveFitOutputEntity curveFitEntity = new()
            {
                Identifier = $"FIT-LIGAMENT-{Guid.NewGuid():N}",
                ExtenalIdentifier = "LCA-PIG-01",
                MechanicalModelName = "Fung",
                InitialAcceptedRange = 0.0,
                FinalAcceptedRange = 12.5,
                LoadResponseRelationship = LoadResponseRelationship.StressStrain,
                RampTimeConsideration = RampTimeConsideration.ConsiderWithViscoelasticEffect,
                ViscoelasticEffect = ViscoelasticEffect.Relaxation,
                Error = 0.00035,
                Iterations = 28,
                ConstitutiveParameters = "{\"c\": 1.25, \"A\": 0.85, \"B\": 12.4}"
            };

            // INSERT
            long insertedFitId = await repository.InsertAsync(curveFitEntity);
            Assert.True(insertedFitId > 0, "InsertAsync must return a positive primary key for curve fit outputs.");

            // SELECT
            MechanicalModelCurveFitOutputEntity? fetchedFit = await repository.GetAsync<MechanicalModelCurveFitOutputEntity>(insertedFitId);
            Assert.NotNull(fetchedFit);
            Assert.Equal(curveFitEntity.Identifier, fetchedFit.Identifier);
            Assert.Equal("Fung", fetchedFit.MechanicalModelName);
            Assert.Equal(0.00035, fetchedFit.Error);
            Assert.Equal("{\"c\": 1.25, \"A\": 0.85, \"B\": 12.4}", fetchedFit.ConstitutiveParameters);

            // UPDATE
            MechanicalModelCurveFitOutputEntity modifiedFit = fetchedFit with
            {
                Error = 0.00018,
                Iterations = 35,
                ConstitutiveParameters = "{\"c\": 1.28, \"A\": 0.89, \"B\": 12.9}"
            };
            bool fitUpdated = await repository.TryUpdateAsync(modifiedFit);
            Assert.True(fitUpdated, "TryUpdateAsync must return true when updating curve fit output.");

            MechanicalModelCurveFitOutputEntity? fetchedUpdatedFit = await repository.GetAsync<MechanicalModelCurveFitOutputEntity>(insertedFitId);
            Assert.NotNull(fetchedUpdatedFit);
            Assert.Equal(0.00018, fetchedUpdatedFit.Error);
            Assert.Equal(35, fetchedUpdatedFit.Iterations);
            Assert.Equal("{\"c\": 1.28, \"A\": 0.89, \"B\": 12.9}", fetchedUpdatedFit.ConstitutiveParameters);

            // DELETE
            await repository.DeleteAsync<MechanicalModelCurveFitOutputEntity>(insertedFitId);
            MechanicalModelCurveFitOutputEntity? fetchedDeletedFit = await repository.GetAsync<MechanicalModelCurveFitOutputEntity>(insertedFitId);
            Assert.Null(fetchedDeletedFit);
        }
        finally
        {
            if (container is not null)
            {
                await container.DisposeAsync();
            }
        }
    }
}
