using MelloSilveiraTools.Core.Managers.File.Csv;
using MelloSilveiraTools.Core.Managers.File.Models;
using MelloSilveiraTools.Core.Managers.File.Providers;
using MelloSilveiraTools.Core.Pipelines.Steps;
using MelloSilveiraTools.MechanicsOfMaterials.Optimizations.SensitivityAnalyses.Models;
using System.Collections.Concurrent;

namespace MelloSilveiraTools.MechanicsOfMaterials.Optimizations.Pipelines.SensitivityAnalysis.Steps;

/// <summary>
/// Pipeline step that partitions evaluated parametric sweep payloads by variable name
/// and serializes each variable's sensitivity results into a dedicated CSV file.
/// </summary>
/// <param name="fileStorageService">Storage service responsible for resolving paths and opening file streams.</param>
/// <param name="identifier">Mandatory unique business identifier partitioning the generated sensitivity CSV files.</param>
public sealed class ParametricSweepCsvWriterStep(
    IFileStorageService fileStorageService,
    string identifier)
    : IAsyncPipelineStep<ParametricSweepFinalPayload>,
      IAsyncPipelineStep<ParametricSweepFinalPayload, ParametricSweepFinalPayload>
{
    private const string Context = "SensitivityAnalysis";
    private const string CsvHeader = "VariableValue,InitialStress,FinalStress,AbsoluteDeltaStress,PercentageDeltaStress,AsymptoteTime";

    private readonly ConcurrentDictionary<string, Task<SweepWriterEntry>> _writerTasks = [];
    private readonly ConcurrentDictionary<string, StorageEntryMetadata> _generatedMetadata = [];
    private bool _disposed;

    /// <inheritdoc />
    public string Name => nameof(ParametricSweepCsvWriterStep);

    /// <summary>
    /// Gets the collection of storage entry metadata snapshots for all partitioned sensitivity CSV files generated by this writer step.
    /// </summary>
    public IReadOnlyCollection<StorageEntryMetadata> GeneratedFilesMetadata => [.. _generatedMetadata.Values];

    /// <inheritdoc />
    public async Task<ParametricSweepFinalPayload> ExecuteAsync(ParametricSweepFinalPayload input, CancellationToken cancellationToken = default)
    {
        cancellationToken.ThrowIfCancellationRequested();

        SweepWriterEntry entry = await GetOrCreateWriterEntryAsync(input.VariableName, cancellationToken).ConfigureAwait(false);

        await entry.Lock.WaitAsync(cancellationToken).ConfigureAwait(false);
        try
        {
            string row = FormattableString.Invariant($"{input.VariableValue:G},{input.InitialStress:G},{input.FinalStress:G},{input.AbsoluteDeltaStress:G},{input.PercentageDeltaStress:G},{input.AsymptoteTime:G}");
            await entry.Writer.WriteRowAsync(row, cancellationToken).ConfigureAwait(false);
        }
        finally
        {
            entry.Lock.Release();
        }

        return input;
    }

    /// <inheritdoc />
    async Task IAsyncPipelineStep<ParametricSweepFinalPayload>.ExecuteAsync(ParametricSweepFinalPayload input, CancellationToken cancellationToken)
    {
        await ExecuteAsync(input, cancellationToken).ConfigureAwait(false);
    }

    /// <summary>
    /// Executes the step on a collection of payloads, grouping them by variable name and writing each partition into its dedicated CSV file.
    /// </summary>
    /// <param name="payloads">The collection of evaluated sensitivity payloads.</param>
    /// <param name="cancellationToken">Cooperative cancellation token.</param>
    /// <returns>A collection of storage entry metadata for all partitioned CSV files written.</returns>
    public async Task<IReadOnlyCollection<StorageEntryMetadata>> ExecuteAsync(
        IEnumerable<ParametricSweepFinalPayload> payloads,
        CancellationToken cancellationToken = default)
    {
        cancellationToken.ThrowIfCancellationRequested();

        foreach (ParametricSweepFinalPayload payload in payloads)
        {
            await ExecuteAsync(payload, cancellationToken).ConfigureAwait(false);
        }

        await DisposeAsync().ConfigureAwait(false);
        return GeneratedFilesMetadata;
    }

    /// <inheritdoc />
    public async ValueTask DisposeAsync()
    {
        if (_disposed)
        {
            return;
        }

        _disposed = true;

        List<Exception> exceptions = [];

        foreach (Task<SweepWriterEntry> task in _writerTasks.Values)
        {
            try
            {
                SweepWriterEntry entry = await task.ConfigureAwait(false);
                await entry.DisposeAsync().ConfigureAwait(false);
                StorageEntryMetadata metadata = await fileStorageService
                    .GetMetadataAsync(entry.Location, CancellationToken.None)
                    .ConfigureAwait(false);
                _generatedMetadata[entry.FileName] = metadata;
            }
            catch (Exception ex)
            {
                exceptions.Add(ex);
            }
        }

        if (exceptions.Count > 0)
        {
            throw new AggregateException("Failed to dispose one or more sensitivity sweep CSV writers.", exceptions);
        }

        GC.SuppressFinalize(this);
    }

    private async Task<SweepWriterEntry> GetOrCreateWriterEntryAsync(string variableName, CancellationToken cancellationToken)
    {
        while (true)
        {
            if (_writerTasks.TryGetValue(variableName, out Task<SweepWriterEntry>? existingTask))
            {
                try
                {
                    return await existingTask.ConfigureAwait(false);
                }
                catch when (!existingTask.IsCompletedSuccessfully)
                {
                    _writerTasks.TryRemove(new KeyValuePair<string, Task<SweepWriterEntry>>(variableName, existingTask));
                    throw;
                }
            }

            TaskCompletionSource<SweepWriterEntry> tcs = new(TaskCreationOptions.RunContinuationsAsynchronously);
            if (_writerTasks.TryAdd(variableName, tcs.Task))
            {
                try
                {
                    SweepWriterEntry entry = await CreateWriterEntryAsync(variableName, cancellationToken).ConfigureAwait(false);
                    tcs.TrySetResult(entry);
                    return entry;
                }
                catch (Exception ex)
                {
                    _writerTasks.TryRemove(new KeyValuePair<string, Task<SweepWriterEntry>>(variableName, tcs.Task));
                    tcs.TrySetException(ex);
                    throw;
                }
            }
        }
    }

    private async Task<SweepWriterEntry> CreateWriterEntryAsync(string variableName, CancellationToken cancellationToken)
    {
        string fileName = $"{variableName}_SensitivityAnalysis{FileExtensions.CommaSeparatedValues}";
        (Stream stream, string location) = await fileStorageService
            .CreateWriteAsync(identifier, Context, fileName, cancellationToken)
            .ConfigureAwait(false);
        CsvFileWriter writer = new(stream, CsvHeader);
        return new SweepWriterEntry(fileName, location, stream, writer);
    }

    private sealed class SweepWriterEntry(string fileName, string location, Stream stream, CsvFileWriter writer) : IAsyncDisposable
    {
        public string FileName => fileName;
        public string Location => location;
        public Stream Stream => stream;
        public CsvFileWriter Writer => writer;
        public SemaphoreSlim Lock { get; } = new(1, 1);

        public async ValueTask DisposeAsync()
        {
            await Lock.WaitAsync().ConfigureAwait(false);
            try
            {
                await writer.DisposeAsync().ConfigureAwait(false);
                await stream.DisposeAsync().ConfigureAwait(false);
            }
            finally
            {
                Lock.Release();
                Lock.Dispose();
            }
        }
    }
}
