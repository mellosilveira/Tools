using MelloSilveiraTools.Core.Managers.File;
using MelloSilveiraTools.Core.Pipelines.Steps;
using MelloSilveiraTools.MechanicsOfMaterials.Optimizations.SensitivityAnalyses.Models;
using Microsoft.AspNetCore.Http;
using System.Collections.Concurrent;
using System.Globalization;

namespace MelloSilveiraTools.MechanicsOfMaterials.Optimizations.Pipelines.SensitivityAnalysis.Steps;

/// <summary>
/// A terminal I/O boundary step that consumes strictly formatted payloads and partitions 
/// the numerical results into segregated CSV files based on the evaluated variable.
/// Maintains open stream buffers during the execution for high performance.
/// </summary>
/// <remarks>
/// Initializes a new instance of the <see cref="ParametricSweepCsvWriterStep"/> class.
/// </remarks>
/// <param name="outputDirectory">Directory path or storage context where segregated sensitivity CSV files will be written.</param>
/// <param name="fileStorageService">Optional storage service. Defaults to <see cref="LocalFileStorageService"/> if omitted.</param>
public sealed class ParametricSweepCsvWriterStep(
    string outputDirectory,
    IFileStorageService? fileStorageService = null)
    : IAsyncPipelineStep<ParametricSweepFinalPayload>
{
    private const string CsvHeader = "VariableValue,InitialStress,FinalStress,AsymptoteTime,AsymptoteStress,AbsoluteDeltaStress,PercentageDeltaStress";
    private readonly IFileStorageService _fileService = fileStorageService ?? new LocalFileStorageService();
    private readonly ConcurrentDictionary<string, SweepWriterEntry> _writers = [];

    private sealed record SweepWriterEntry(string FilePath, CsvFileWriter Writer);

    /// <inheritdoc />
    public string Name => nameof(ParametricSweepCsvWriterStep);

    /// <summary>
    /// Gets the collection of full file paths generated by this writer step.
    /// </summary>
    public IReadOnlyCollection<string> GeneratedFilePaths => [.. _writers.Values.Select(entry => entry.FilePath)];

    /// <summary>
    /// Gets the collection of file metadata snapshots generated by this writer step.
    /// </summary>
    public IReadOnlyCollection<FileMetadata> GeneratedFilesMetadata =>
        [.. _writers.Values.Select(entry => _fileService.GetMetadata(entry.FilePath))];

    /// <summary>
    /// Appends a single sensitivity payload (convenience overload for direct execution and unit testing).
    /// </summary>
    public async Task ExecuteAsync(ParametricSweepFinalPayload input, CancellationToken cancellationToken = default)
    {
        cancellationToken.ThrowIfCancellationRequested();

        SweepWriterEntry entry = _writers.GetOrAdd(input.VariableName, variableName =>
        {
            string filePath = Path.IsPathRooted(outputDirectory)
                ? Path.Combine(outputDirectory, $"{variableName}_SensitivityAnalysis.csv")
                : _fileService.ResolvePath(string.IsNullOrWhiteSpace(outputDirectory) ? "SensitivityAnalysis" : outputDirectory, variableName, $"{variableName}_SensitivityAnalysis.csv");

            Stream stream = _fileService.OpenWrite(filePath);
            CsvFileWriter writer = new(stream, CsvHeader);
            return new SweepWriterEntry(filePath, writer);
        });

        string row = string.Format(
            CultureInfo.InvariantCulture,
            "{0:G},{1:G},{2:G},{3:G},{4:G},{5:G},{6:G}",
            input.VariableValue,
            input.InitialStress,
            input.FinalStress,
            input.AsymptoteTime,
            input.AsymptoteStress,
            input.AbsoluteDeltaStress,
            input.PercentageDeltaStress);

        await entry.Writer.WriteRowAsync(row, cancellationToken).ConfigureAwait(false);
    }

    /// <inheritdoc />
    public async ValueTask DisposeAsync()
    {
        List<Exception> exceptions = [];
        foreach (IAsyncDisposable session in _writers.Values.Select(entry => entry.Writer))
        {
            try
            {
                await session.DisposeAsync().ConfigureAwait(false);
            }
            catch (Exception ex)
            {
                exceptions.Add(ex);
            }
        }

        if (exceptions.Count > 0)
        {
            throw new AggregateException(exceptions);
        }
        GC.SuppressFinalize(this);
    }
}
