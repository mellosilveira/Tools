using MelloSilveiraTools.Core.Managers.File;
using MelloSilveiraTools.Core.Pipelines.Steps;
using MelloSilveiraTools.MechanicsOfMaterials.Optimizations.SensitivityAnalyses.Models;
using System.Collections.Concurrent;
using System.Globalization;

namespace MelloSilveiraTools.MechanicsOfMaterials.Optimizations.Pipelines.SensitivityAnalysis.Steps;

/// <summary>
/// A terminal I/O boundary step that consumes strictly formatted payloads and partitions 
/// the numerical results into segregated CSV files based on the evaluated variable.
/// Maintains open stream buffers during the execution for high performance.
/// </summary>
/// <remarks>
/// Initializes a new instance of the <see cref="ParametricSweepCsvWriterStep"/> class.
/// </remarks>
/// <param name="outputDirectory">Directory path where segregated sensitivity CSV files will be written.</param>
public sealed class ParametricSweepCsvWriterStep(string outputDirectory) : IAsyncPipelineStep<ParametricSweepFinalPayload>
{
    private const string CsvHeader = "VariableValue,InitialStress,FinalStress,AsymptoteTime,AsymptoteStress,AbsoluteDeltaStress,PercentageDeltaStress";
    private readonly ConcurrentDictionary<string, CsvFileWriter> _writers = [];

    /// <inheritdoc />
    public string Name => nameof(ParametricSweepCsvWriterStep);

    /// <summary>
    /// Gets the collection of full file paths generated by this writer step.
    /// </summary>
    public IReadOnlyCollection<string> GeneratedFilePaths => [.. _writers.Values.Select(s => s.FilePath)];

    /// <summary>
    /// Appends a single sensitivity payload (convenience overload for direct execution and unit testing).
    /// </summary>
    public async Task ExecuteAsync(ParametricSweepFinalPayload input, CancellationToken cancellationToken = default)
    {
        cancellationToken.ThrowIfCancellationRequested();

        CsvFileWriter fileWriter = _writers.GetOrAdd(input.VariableName, variableName =>
        {
            string filePath = Path.Combine(outputDirectory, $"{variableName}_SensitivityAnalysis.csv");
            return new CsvFileWriter(filePath, CsvHeader);
        });

        string row = string.Format(
            CultureInfo.InvariantCulture,
            "{0:G},{1:G},{2:G},{3:G},{4:G},{5:G},{6:G}",
            input.VariableValue,
            input.InitialStress,
            input.FinalStress,
            input.AsymptoteTime,
            input.AsymptoteStress,
            input.AbsoluteDeltaStress,
            input.PercentageDeltaStress);

        await fileWriter.WriteRowAsync(row, cancellationToken).ConfigureAwait(false);
    }

    /// <inheritdoc />
    public async ValueTask DisposeAsync()
    {
        List<Exception> exceptions = [];
        foreach ((_, IAsyncDisposable writer) in _writers)
        {
            try
            {
                await writer.DisposeAsync().ConfigureAwait(false);
            }
            catch (Exception ex)
            {
                exceptions.Add(ex);
            }
        }

        if (exceptions.Count > 0)
        {
            throw new AggregateException(exceptions);
        }

        GC.SuppressFinalize(this);
    }
}
