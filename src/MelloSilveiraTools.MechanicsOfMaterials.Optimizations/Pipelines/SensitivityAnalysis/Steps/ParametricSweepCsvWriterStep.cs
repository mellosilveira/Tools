using MelloSilveiraTools.Core.Managers.File;
using MelloSilveiraTools.Core.Pipelines.Steps;
using MelloSilveiraTools.MechanicsOfMaterials.Optimizations.SensitivityAnalyses.Models;
using System.Collections.Concurrent;
using System.Globalization;

namespace MelloSilveiraTools.MechanicsOfMaterials.Optimizations.Pipelines.SensitivityAnalysis.Steps;

/// <summary>
/// A terminal I/O boundary step that consumes strictly formatted payloads and partitions 
/// the numerical results into segregated CSV files based on the evaluated variable.
/// Maintains open stream buffers during the execution for high performance.
/// </summary>
/// <param name="fileStorageService">Storage service responsible for resolving paths and opening file streams.</param>
/// <param name="identifier">Mandatory unique business identifier partitioning the generated sensitivity CSV files.</param>
public sealed class ParametricSweepCsvWriterStep(
    IFileStorageService fileStorageService,
    string identifier)
    : IAsyncPipelineStep<ParametricSweepFinalPayload>, IAsyncPipelineStep<ParametricSweepFinalPayload, ParametricSweepFinalPayload>
{
    // TODO: REVISAR
    
    private const string Context = "SensitivityAnalysis";
    private const string CsvHeader = "VariableValue,InitialStress,FinalStress,AsymptoteTime,AsymptoteStress,AbsoluteDeltaStress,PercentageDeltaStress";
    private readonly ConcurrentDictionary<string, SweepWriterEntry> _writers = [];

    private sealed record SweepWriterEntry(string FileName, CsvFileWriter Writer);

    /// <inheritdoc />
    public string Name => nameof(ParametricSweepCsvWriterStep);

    /// <summary>
    /// Gets the collection of file metadata snapshots generated by this writer step.
    /// </summary>
    public IReadOnlyCollection<FileMetadata> GeneratedFilesMetadata =>
        [.. _writers.Values.Select(entry => fileStorageService.GetMetadata(Context, identifier, entry.FileName))];

    /// <summary>
    /// Appends a single sensitivity payload to its variable-specific CSV stream.
    /// </summary>
    /// <param name="input">The sensitivity evaluation payload to write.</param>
    /// <param name="cancellationToken">Cooperative cancellation token.</param>
    public async Task ExecuteAsync(ParametricSweepFinalPayload input, CancellationToken cancellationToken = default)
    {
        cancellationToken.ThrowIfCancellationRequested();

        SweepWriterEntry entry = _writers.GetOrAdd(input.VariableName, variableName =>
        {
            string fileName = $"{variableName}_SensitivityAnalysis{FileExtensions.CommaSeparatedValues}";
            (Stream stream, FileMetadata _) = fileStorageService.Create(Context, identifier, fileName);
            CsvFileWriter writer = new(stream, CsvHeader);
            return new SweepWriterEntry(fileName, writer);
        });

        string row = FormattableString.Invariant($"{input.VariableValue:G},{input.InitialStress:G},{input.FinalStress:G},{input.AsymptoteTime:G},{input.AsymptoteStress:G},{input.AbsoluteDeltaStress:G},{input.PercentageDeltaStress:G}");

        await entry.Writer.WriteRowAsync(row, cancellationToken).ConfigureAwait(false);
    }

    /// <inheritdoc />
    async Task<ParametricSweepFinalPayload> IAsyncPipelineStep<ParametricSweepFinalPayload, ParametricSweepFinalPayload>.ExecuteAsync(
        ParametricSweepFinalPayload input,
        CancellationToken cancellationToken)
    {
        await ExecuteAsync(input, cancellationToken).ConfigureAwait(false);
        return input;
    }

    private bool _disposed;

    /// <inheritdoc />
    public async ValueTask DisposeAsync()
    {
        if (_disposed)
        {
            return;
        }

        _disposed = true;

        foreach (SweepWriterEntry entry in _writers.Values)
        {
            await entry.Writer.DisposeAsync().ConfigureAwait(false);
        }

        GC.SuppressFinalize(this);
    }
}
