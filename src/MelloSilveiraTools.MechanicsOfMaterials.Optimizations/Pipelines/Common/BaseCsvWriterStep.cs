using MelloSilveiraTools.Core.Pipelines.Steps;
using System.Text;

namespace MelloSilveiraTools.MechanicsOfMaterials.Optimizations.Pipelines.Common;

/// <summary>
/// Abstract base class for pipeline steps that produce CSV files on disk.
/// Centralizes stream options, high-throughput batching, invariant formatting, and file path tracking.
/// </summary>
public abstract class BaseCsvWriterStep : IPipelineStep, IAsyncDisposable
{
    /// <summary>
    /// Buffer size (128 KB) for FileStream and StreamWriter operations.
    /// </summary>
    protected const int BufferSize = 128 * 1024;

    /// <summary>
    /// Row threshold before flushing buffered lines to disk.
    /// </summary>
    protected const int BatchThreshold = 1000;

    /// <summary>
    /// Initial capacity (16 KB) for row string buffers.
    /// </summary>
    protected const int BufferCapacity = 16 * 1024;

    /// <summary>
    /// Standard delimiter for CSV columns.
    /// </summary>
    protected const char Delimiter = ',';

    /// <summary>
    /// UTF-8 encoding without byte order mark (BOM).
    /// </summary>
    protected static readonly Encoding Utf8Encoding = new UTF8Encoding(false);

    /// <inheritdoc />
    public abstract string Name { get; }

    /// <summary>
    /// Gets the full path of the primary generated CSV file, or empty if not yet generated.
    /// </summary>
    public abstract string OutputFullFileName { get; }

    /// <summary>
    /// Gets the collection of full file paths generated by this writer step.
    /// </summary>
    public virtual IReadOnlyCollection<string> GeneratedFilePaths =>
        string.IsNullOrEmpty(OutputFullFileName) ? [] : [OutputFullFileName];

    /// <summary>
    /// Creates a directory if missing and opens a StreamWriter configured for sequential asynchronous CSV writing.
    /// </summary>
    /// <param name="filePath">Target destination file path.</param>
    /// <param name="bufferSize">Internal buffer size for the underlying stream. Defaults to 128 KB.</param>
    /// <returns>A configured StreamWriter.</returns>
    protected static StreamWriter CreateWriter(string filePath, int bufferSize = BufferSize)
    {
        string? directory = Path.GetDirectoryName(filePath);
        if (!string.IsNullOrEmpty(directory) && !Directory.Exists(directory))
        {
            Directory.CreateDirectory(directory);
        }

        FileStreamOptions options = new()
        {
            Mode = FileMode.Create,
            Access = FileAccess.Write,
            Share = FileShare.None,
            Options = FileOptions.SequentialScan | FileOptions.Asynchronous,
            BufferSize = bufferSize
        };

        FileStream stream = new(filePath, options);
        return new StreamWriter(stream, Utf8Encoding, bufferSize);
    }

    /// <summary>
    /// Appends a CSV row to the buffer and flushes to the stream writer when the batch threshold is reached.
    /// </summary>
    /// <param name="writer">Target stream writer.</param>
    /// <param name="buffer">String buffer accumulating rows.</param>
    /// <param name="batchCount">Current accumulated row count.</param>
    /// <param name="row">Formatted CSV row text.</param>
    /// <param name="cancellationToken">Cancellation token.</param>
    /// <param name="batchThreshold">Row threshold before flushing. Defaults to 1000.</param>
    /// <returns>The updated accumulated row count (0 if flushed, otherwise batchCount + 1).</returns>
    protected static async Task<int> WriteRowAsync(
        StreamWriter writer,
        StringBuilder buffer,
        int batchCount,
        string row,
        CancellationToken cancellationToken,
        int batchThreshold = BatchThreshold)
    {
        buffer.Append(row).Append(Environment.NewLine);

        if (++batchCount >= batchThreshold)
        {
            await writer.WriteAsync(buffer, cancellationToken).ConfigureAwait(false);
            buffer.Clear();
            return 0;
        }

        return batchCount;
    }

    /// <summary>
    /// Emits unwritten header, flushes remaining buffer content, and asynchronously disposes the writer and stream.
    /// </summary>
    /// <param name="writer">Stream writer to flush and dispose.</param>
    /// <param name="buffer">String buffer with potential remaining rows.</param>
    /// <param name="header">Header string to emit if not yet written.</param>
    /// <param name="headerWritten">Whether the header was already written.</param>
    protected static async ValueTask FlushAndDisposeAsync(
        StreamWriter writer,
        StringBuilder buffer,
        string? header = null,
        bool headerWritten = true)
    {
        if (!headerWritten && !string.IsNullOrEmpty(header))
        {
            await writer.WriteLineAsync(header).ConfigureAwait(false);
        }

        if (buffer.Length > 0)
        {
            await writer.WriteAsync(buffer).ConfigureAwait(false);
            buffer.Clear();
        }

        await writer.FlushAsync().ConfigureAwait(false);
        await writer.DisposeAsync().ConfigureAwait(false);
    }

    /// <inheritdoc />
    public abstract ValueTask DisposeAsync();
}
