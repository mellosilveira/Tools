using MelloSilveiraTools.Core.Managers.File;
using MelloSilveiraTools.Core.Pipelines.Steps;
using MelloSilveiraTools.MechanicsOfMaterials.Optimizations.Pipelines.ExperimentalData.Models;
using System.Globalization;

namespace MelloSilveiraTools.MechanicsOfMaterials.Optimizations.Pipelines.ExperimentalData.Steps;

/// <summary>
/// Pipeline step responsible for persisting processed experimental data points to a CSV file.
/// Writes the CSV header upon initialization and sequentially appends each data point line in batches.
/// </summary>
public sealed class ExperimentalDataFileWriterStep : IAsyncPipelineStep<SegmentedDataPoint>
{
    private const string CsvHeader = "Time,Strain,StrainRate,StrainAcceleration,Stress,StressRate,StressAcceleration";
    private readonly CsvFileWriter _session;

    /// <summary>
    /// Initializes a new instance of the <see cref="ExperimentalDataFileWriterStep"/> class.
    /// </summary>
    /// <param name="fileManager">File manager used to resolve the destination file path.</param>
    /// <param name="uri">Target destination directory URI.</param>
    /// <param name="identifier">Unique business identifier prefix for the generated file.</param>
    public ExperimentalDataFileWriterStep(IFileManager fileManager, string uri, string identifier)
    {
        string fullFileName = fileManager.BuildTimebasedFullName(uri, identifier, FileExtensions.CommaSeparatedValues);
        _session = new CsvFileWriter(fullFileName, CsvHeader);
        GeneratedFilePaths = [fullFileName];
    }

    /// <inheritdoc />
    public string Name => "ExperimentalDataFileWriter";

    /// <summary>
    /// Gets the collection of full file paths generated by this writer step.
    /// </summary>
    public IReadOnlyCollection<string> GeneratedFilePaths { get; }

    /// <inheritdoc />
    public async Task ExecuteAsync(SegmentedDataPoint input, CancellationToken cancellationToken = default)
    {
        ProcessedDataPoint point = input.ProcessedDataPoint;
        string row = string.Format(
            CultureInfo.InvariantCulture,
            "{0},{1},{2},{3},{4},{5},{6}",
            point.Time,
            point.Strain,
            point.StrainRate,
            point.StrainAcceleration,
            point.Stress,
            point.StressRate,
            point.StressAcceleration);

        await _session.WriteRowAsync(row, cancellationToken).ConfigureAwait(false);
    }

    /// <inheritdoc />
    public async ValueTask DisposeAsync()
    {
        await _session.DisposeAsync().ConfigureAwait(false);
        GC.SuppressFinalize(this);
    }
}
