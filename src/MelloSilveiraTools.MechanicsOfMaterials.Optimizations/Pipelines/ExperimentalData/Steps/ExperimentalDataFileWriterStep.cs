using MelloSilveiraTools.Core.Managers.File.Csv;
using MelloSilveiraTools.Core.Managers.File.Models;
using MelloSilveiraTools.Core.Managers.File.Providers;
using MelloSilveiraTools.Core.Models;
using MelloSilveiraTools.Core.Pipelines.Steps;
using MelloSilveiraTools.MechanicsOfMaterials.Optimizations.CurveFitting.Models;
using MelloSilveiraTools.MechanicsOfMaterials.Optimizations.Pipelines.ExperimentalData.Models;
using System.Runtime.CompilerServices;

namespace MelloSilveiraTools.MechanicsOfMaterials.Optimizations.Pipelines.ExperimentalData.Steps;

/// <summary>
/// Pipeline step responsible for streaming processed experimental data points to a CSV file
/// and emitting the finalized <see cref="StorageEntryMetadata"/> upon receiving the end-of-stream marker.
/// </summary>
/// <param name="fileStorageService">Storage service responsible for resolving paths and opening file streams.</param>
/// <param name="identifier">Mandatory unique business identifier prefix for the generated file.</param>
public sealed class ExperimentalDataFileWriterStep(IFileStorageService fileStorageService, string identifier)
    : IAsyncEnumerablePipelineStep<SegmentedDataPoint, StorageEntryMetadata>
{
    private const string Context = "ExperimentalData";
    private const string CsvHeader = "Time,Strain,StrainRate,StrainAcceleration,Stress,StressRate,StressAcceleration";
    private string? _location;
    private CsvFileWriter? _writer;
    private bool _writerClosed;

    /// <inheritdoc />
    public string Name => nameof(ExperimentalDataFileWriterStep);

    /// <summary>
    /// Gets the canonical storage location of the file generated by this writer step, or <c>null</c> if not yet initialized.
    /// </summary>
    public string? Location => _location;

    private ExperimentalDataFileWriterStep(IFileStorageService fileStorageService, string identifier, string location, CsvFileWriter writer)
        : this(fileStorageService, identifier)
    {
        _location = location;
        _writer = writer;
    }

    /// <summary>
    /// Asynchronously creates and eagerly initializes a new instance of <see cref="ExperimentalDataFileWriterStep"/>.
    /// </summary>
    /// <param name="fileStorageService">Storage service responsible for resolving paths and opening file streams.</param>
    /// <param name="identifier">Mandatory unique business identifier prefix for the generated file.</param>
    /// <param name="cancellationToken">Cancellation token.</param>
    /// <returns>A task returning the initialized writer step.</returns>
    public static async Task<ExperimentalDataFileWriterStep> CreateAsync(
        IFileStorageService fileStorageService,
        string identifier,
        CancellationToken cancellationToken = default)
    {
        (Stream fileStream, string location) = await fileStorageService.CreateWriteTimebasedAsync(
            Context,
            identifier,
            FileExtensions.CommaSeparatedValues,
            cancellationToken: cancellationToken).ConfigureAwait(false);

        CsvFileWriter writer = new(fileStream, CsvHeader);
        return new ExperimentalDataFileWriterStep(fileStorageService, identifier, location, writer);
    }

    /// <summary>
    /// Flushes and closes the underlying CSV stream (if still open) and retrieves the storage entry metadata snapshot.
    /// </summary>
    /// <param name="cancellationToken">Cancellation token.</param>
    /// <returns>A value task returning the storage entry metadata snapshot.</returns>
    public async ValueTask<StorageEntryMetadata> GetMetadataAsync(CancellationToken cancellationToken = default)
    {
        await EnsureInitializedAsync(cancellationToken).ConfigureAwait(false);
        await CloseWriterAsync().ConfigureAwait(false);
        return await fileStorageService.GetMetadataAsync(_location!, cancellationToken).ConfigureAwait(false);
    }

    /// <inheritdoc />
    public async IAsyncEnumerable<StorageEntryMetadata> ExecuteAsync(
        SegmentedDataPoint input,
        [EnumeratorCancellation] CancellationToken cancellationToken = default)
    {
        await EnsureInitializedAsync(cancellationToken).ConfigureAwait(false);

        if (input.SegmentType == SegmentType.Unknown)
        {
            yield return await GetMetadataAsync(cancellationToken).ConfigureAwait(false);
            yield break;
        }

        ProcessedDataPoint point = input.ProcessedDataPoint;
        string row = FormattableString.Invariant($"{point.Time:G7},{point.Strain:G7},{point.StrainRate:G7},{point.StrainAcceleration:G7},{point.Stress:G7},{point.StressRate:G7},{point.StressAcceleration:G7}");
        await _writer!.WriteRowAsync(row, cancellationToken).ConfigureAwait(false);
    }

    private async ValueTask EnsureInitializedAsync(CancellationToken cancellationToken)
    {
        if (_writer is not null)
            return;

        (Stream fileStream, string location) = await fileStorageService.CreateWriteTimebasedAsync(
            Context,
            identifier,
            FileExtensions.CommaSeparatedValues,
            cancellationToken: cancellationToken).ConfigureAwait(false);

        _location = location;
        _writer = new CsvFileWriter(fileStream, CsvHeader);
    }

    private async ValueTask CloseWriterAsync()
    {
        if (_writerClosed || _writer is null)
            return;

        _writerClosed = true;
        await _writer.DisposeAsync().ConfigureAwait(false);
    }

    /// <inheritdoc />
    public async ValueTask DisposeAsync()
    {
        await CloseWriterAsync().ConfigureAwait(false);
        GC.SuppressFinalize(this);
    }
}
