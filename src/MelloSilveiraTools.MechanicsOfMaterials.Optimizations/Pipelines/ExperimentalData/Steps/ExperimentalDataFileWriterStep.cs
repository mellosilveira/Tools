using MelloSilveiraTools.Core.Managers.File;
using MelloSilveiraTools.Core.Pipelines.Steps;
using MelloSilveiraTools.MechanicsOfMaterials.Optimizations.Pipelines.ExperimentalData.Models;
using System.Globalization;

namespace MelloSilveiraTools.MechanicsOfMaterials.Optimizations.Pipelines.ExperimentalData.Steps;

/// <summary>
/// Pipeline step responsible for persisting processed experimental data points to a CSV file.
/// Writes the CSV header upon initialization and sequentially appends each data point line in batches.
/// </summary>
/// <param name="fileStorageService">Storage service responsible for resolving paths and opening file streams.</param>
/// <param name="identifier">Mandatory unique business identifier prefix for the generated file.</param>
public sealed class ExperimentalDataFileWriterStep(
    IFileStorageService fileStorageService,
    string identifier)
    : IAsyncPipelineStep<SegmentedDataPoint>
{
    private const string Context = "ExperimentalData";
    private const string CsvHeader = "Time,Strain,StrainRate,StrainAcceleration,Stress,StressRate,StressAcceleration";

    private readonly CsvFileWriter _writer = new(
        fileStorageService.OpenWrite(Context, identifier, $"{identifier}{FileExtensions.CommaSeparatedValues}"),
        CsvHeader);

    /// <inheritdoc />
    public string Name => nameof(ExperimentalDataFileWriterStep);

    /// <summary>
    /// Gets the metadata of the file generated by this writer step.
    /// </summary>
    public FileMetadata FileMetadata => fileStorageService.GetMetadata(
        Context,
        identifier,
        $"{identifier}{FileExtensions.CommaSeparatedValues}");

    /// <inheritdoc />
    public async Task ExecuteAsync(SegmentedDataPoint input, CancellationToken cancellationToken = default)
    {
        ProcessedDataPoint point = input.ProcessedDataPoint;
        string row = string.Format(
            CultureInfo.InvariantCulture,
            "{0},{1},{2},{3},{4},{5},{6}",
            point.Time,
            point.Strain,
            point.StrainRate,
            point.StrainAcceleration,
            point.Stress,
            point.StressRate,
            point.StressAcceleration);

        await _writer.WriteRowAsync(row, cancellationToken).ConfigureAwait(false);
    }

    /// <inheritdoc />
    public async ValueTask DisposeAsync()
    {
        await _writer.DisposeAsync().ConfigureAwait(false);
        GC.SuppressFinalize(this);
    }
}
