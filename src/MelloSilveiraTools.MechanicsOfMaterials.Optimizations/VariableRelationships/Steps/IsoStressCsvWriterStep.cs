using MelloSilveiraTools.Core.Managers.File.Csv;
using MelloSilveiraTools.Core.Managers.File.Models;
using MelloSilveiraTools.Core.Managers.File.Providers;
using MelloSilveiraTools.Core.Pipelines.Steps;
using MelloSilveiraTools.MechanicsOfMaterials.Optimizations.VariableRelationships.Models;

namespace MelloSilveiraTools.MechanicsOfMaterials.Optimizations.VariableRelationships.Steps;

/// <summary>
/// Pipeline step that writes accepted iso-stress parameter combinations to a persistent CSV artifact
/// named <c>{Identifier}_IsoStress_Combinations.csv</c> partitioned under the <c>VariableRelationships</c> storage context.
/// </summary>
public sealed class IsoStressCsvWriterStep :
    IAsyncPipelineStep<VariableCombinationPoint, VariableCombinationPoint>,
    IAsyncPipelineStep<VariableCombinationPoint>
{
    private const string StorageContext = "VariableRelationships";

    private readonly IFileStorageService _fileStorageService;
    private readonly string _identifier;
    private readonly IReadOnlyList<string>? _configuredParameterNames;
    private readonly SemaphoreSlim _lock = new(1, 1);

    private Stream? _stream;
    private CsvFileWriter? _writer;
    private string? _location;
    private StorageEntryMetadata? _metadata;
    private IReadOnlyList<string>? _resolvedParameterNames;
    private bool _disposed;

    /// <summary>
    /// Initializes a new instance of the <see cref="IsoStressCsvWriterStep"/> class.
    /// </summary>
    /// <param name="fileStorageService">The file storage service abstraction.</param>
    /// <param name="identifier">Unique correlation identifier partitioning the generated CSV file.</param>
    /// <param name="parameterBounds">Optional collection of parameter bounds used to predetermine column ordering.</param>
    public IsoStressCsvWriterStep(
        IFileStorageService fileStorageService,
        string identifier,
        IReadOnlyList<ParameterBound>? parameterBounds = null)
    {
        ArgumentNullException.ThrowIfNull(fileStorageService);
        ArgumentException.ThrowIfNullOrWhiteSpace(identifier);

        _fileStorageService = fileStorageService;
        _identifier = identifier;

        if (parameterBounds is not null && parameterBounds.Count > 0)
        {
            List<string> sortedNames = [];
            for (int i = 0; i < parameterBounds.Count; i++)
            {
                sortedNames.Add(parameterBounds[i].ParameterName);
            }

            sortedNames.Sort(StringComparer.Ordinal);
            _configuredParameterNames = sortedNames;
        }
    }

    /// <inheritdoc />
    public string Name => nameof(IsoStressCsvWriterStep);

    /// <summary>
    /// Gets the metadata of the persistent CSV file generated by this writer step.
    /// Available after stream disposal.
    /// </summary>
    public StorageEntryMetadata? GeneratedFileMetadata => _metadata;

    /// <inheritdoc />
    public async Task<VariableCombinationPoint> ExecuteAsync(VariableCombinationPoint input, CancellationToken cancellationToken = default)
    {
        ArgumentNullException.ThrowIfNull(input);
        cancellationToken.ThrowIfCancellationRequested();

        await _lock.WaitAsync(cancellationToken).ConfigureAwait(false);
        try
        {
            if (_writer is null)
            {
                await InitializeWriterAsync(input, cancellationToken).ConfigureAwait(false);
            }

            List<string> rowValues = [];
            for (int i = 0; i < _resolvedParameterNames!.Count; i++)
            {
                string paramName = _resolvedParameterNames[i];
                double paramValue = input.Parameters.TryGetValue(paramName, out double val) ? val : 0.0;
                rowValues.Add(FormattableString.Invariant($"{paramValue:G}"));
            }

            rowValues.Add(FormattableString.Invariant($"{input.CalculatedStress:G}"));
            rowValues.Add(FormattableString.Invariant($"{input.Residual:G}"));

            string row = string.Join(",", rowValues);
            await _writer!.WriteRowAsync(row, cancellationToken).ConfigureAwait(false);
        }
        finally
        {
            _lock.Release();
        }

        return input;
    }

    /// <inheritdoc />
    async Task IAsyncPipelineStep<VariableCombinationPoint>.ExecuteAsync(VariableCombinationPoint input, CancellationToken cancellationToken)
    {
        await ExecuteAsync(input, cancellationToken).ConfigureAwait(false);
    }

    /// <inheritdoc />
    public async ValueTask DisposeAsync()
    {
        if (_disposed)
        {
            return;
        }

        _disposed = true;

        await _lock.WaitAsync(CancellationToken.None).ConfigureAwait(false);
        try
        {
            if (_writer is null)
            {
                await InitializeEmptyWriterAsync(CancellationToken.None).ConfigureAwait(false);
            }

            if (_writer is not null)
            {
                await _writer.DisposeAsync().ConfigureAwait(false);
            }

            if (_stream is not null)
            {
                await _stream.DisposeAsync().ConfigureAwait(false);
            }

            if (!string.IsNullOrEmpty(_location))
            {
                _metadata = await _fileStorageService.GetMetadataAsync(_location, CancellationToken.None).ConfigureAwait(false);
            }
        }
        finally
        {
            _lock.Release();
            _lock.Dispose();
        }

        GC.SuppressFinalize(this);
    }

    private async Task InitializeWriterAsync(VariableCombinationPoint firstPoint, CancellationToken cancellationToken)
    {
        if (_configuredParameterNames is not null)
        {
            _resolvedParameterNames = _configuredParameterNames;
        }
        else
        {
            List<string> names = [.. firstPoint.Parameters.Keys];
            names.Sort(StringComparer.Ordinal);
            _resolvedParameterNames = names;
        }

        string header = string.Join(",", _resolvedParameterNames) + ",CalculatedStress,Residual";
        string fileName = $"{_identifier}_IsoStress_Combinations.csv";

        (Stream stream, string location) = await _fileStorageService
            .CreateWriteAsync(_identifier, StorageContext, fileName, cancellationToken)
            .ConfigureAwait(false);

        _stream = stream;
        _location = location;
        _writer = new CsvFileWriter(_stream, header);
    }

    private async Task InitializeEmptyWriterAsync(CancellationToken cancellationToken)
    {
        List<string> names = _configuredParameterNames is not null ? [.. _configuredParameterNames] : [];
        _resolvedParameterNames = names;

        string header = names.Count > 0
            ? string.Join(",", names) + ",CalculatedStress,Residual"
            : "CalculatedStress,Residual";

        string fileName = $"{_identifier}_IsoStress_Combinations.csv";

        (Stream stream, string location) = await _fileStorageService
            .CreateWriteAsync(_identifier, StorageContext, fileName, cancellationToken)
            .ConfigureAwait(false);

        _stream = stream;
        _location = location;
        _writer = new CsvFileWriter(_stream, header);
    }
}
