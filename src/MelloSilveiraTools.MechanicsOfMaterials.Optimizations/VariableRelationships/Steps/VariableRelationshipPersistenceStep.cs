using MelloSilveiraTools.Core.Models;
using MelloSilveiraTools.Core.Pipelines.Steps;
using MelloSilveiraTools.Database.RelationalDatabase.Models.Entities;
using MelloSilveiraTools.Database.Repositories;
using MelloSilveiraTools.MechanicsOfMaterials.Optimizations.VariableRelationships.Models;
using Microsoft.Extensions.Logging;

namespace MelloSilveiraTools.MechanicsOfMaterials.Optimizations.VariableRelationships.Steps;

/// <summary>
/// Terminal pipeline step that optionally persists execution artifact metadata to the database repository
/// and constructs the final <see cref="VariableRelationshipOutput"/> result payload.
/// </summary>
/// <param name="logger">The structured logger instance.</param>
/// <param name="repository">Optional database repository for tracking generated stored files.</param>
public sealed class VariableRelationshipPersistenceStep(
    ILogger<VariableRelationshipPersistenceStep> logger,
    IRepository? repository = null)
    : IAsyncPipelineStep<VariableRelationshipPersistenceInput, VariableRelationshipOutput>
{
    /// <inheritdoc />
    public string Name => nameof(VariableRelationshipPersistenceStep);

    /// <summary>
    /// Gets the final output generated by this step, available after execution.
    /// </summary>
    public VariableRelationshipOutput? Output { get; private set; }

    /// <inheritdoc />
    public async Task<VariableRelationshipOutput> ExecuteAsync(
        VariableRelationshipPersistenceInput input,
        CancellationToken cancellationToken = default)
    {
        ArgumentNullException.ThrowIfNull(input);
        cancellationToken.ThrowIfCancellationRequested();

        if (repository is not null)
        {
            try
            {
                StorageEntryMetadataEntity fileEntity = StorageEntryMetadataEntity.Create(input.CsvMetadata, input.Identifier);
                Result<long> insertResult = await repository.TryInsertAsync(fileEntity, cancellationToken).ConfigureAwait(false);
                if (insertResult.IsConflict)
                {
                    logger.LogWarning("Stored file entry for variable relationship already exists in repository. Identifier: {Identifier}", input.Identifier);
                }
                else if (!insertResult.Success)
                {
                    logger.LogWarning("Failed to persist stored file entity for variable relationship. Identifier: {Identifier}. Message: {Message}", input.Identifier, insertResult.JoinedMessages);
                }
            }
            catch (Exception ex)
            {
                logger.LogWarning(ex, "Unexpected exception during optional persistence of variable relationship metadata for identifier {Identifier}", input.Identifier);
            }
        }

        VariableRelationshipOutput output = new(
            input.Identifier,
            input.Combinations,
            input.CsvMetadata);

        Output = output;
        return output;
    }

    /// <inheritdoc />
    public ValueTask DisposeAsync()
    {
        GC.SuppressFinalize(this);
        return ValueTask.CompletedTask;
    }
}
