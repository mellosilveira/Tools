using MelloSilveiraTools.Database.RelationalDatabase.Attributes;
using System.Diagnostics.CodeAnalysis;

namespace MelloSilveiraTools.Database.RelationalDatabase.Models.Entities;

/// <summary>
/// Represents an authenticated user account persisted in the <c>users</c> table.
/// </summary>
[Table("users")]
public record UserEntity : EntityBase
{
    /// <summary>
    /// Initializes a new instance of <see cref="UserEntity"/> for persistence mapping and deserialization.
    /// </summary>
    [SetsRequiredMembers]
    public UserEntity()
    {
        Username = string.Empty;
        PasswordHash = string.Empty;
    }

    /// <summary>
    /// Unique user login name.
    /// </summary>
    [Column]
    public required string Username { get; init; }

    /// <summary>
    /// Salted PBKDF2 password hash generated by <c>IEncryptionService</c>.
    /// </summary>
    [Column]
    public required string PasswordHash { get; init; }

    /// <summary>
    /// Indicates whether the user account is active and allowed to authenticate.
    /// </summary>
    [Column]
    public bool IsActive { get; init; } = true;
}
